"""The numbers behind tests/layout.c: sizeof and offsetof for the structures
named in tests/layout.list, measured by compiling one small program against
a header set and reading the values back from the assembler output (nothing
is run, so any m68k GCC will do).

    layout_numbers.py fields INCLUDE_DIR LIST       list every field of LIST's
                                                    structures (ELF GCC, -g)
    layout_numbers.py measure INCLUDE_DIR LIST OUT [defined]
                                                    write "name value" lines
    layout_numbers.py compare OURS THEIRS           exit 1 on any difference
    layout_numbers.py gen PLAIN DEFINED LIST > tests/layout.c

PLAIN is measured as is, DEFINED with -D for each "define" line in LIST
(NEWCLIPRECTS_1_1, which adds struct ClipRect's Flags); gen writes what
both agree on unconditionally and the rest under #ifdef.

Only numbers leave a vendor NDK: names come from LIST, which is ours.
"""
import os
import re
import subprocess
import sys
import tempfile

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import layouts  # noqa: E402  (CC and READELF come from the environment)


def read_list(path):
    incs, defs, structs = [], [], []
    for line in open(path):
        line = line.split("#", 1)[0].split()
        if not line:
            continue
        if line[0] == "include":
            incs += line[1:]
        elif line[0] == "define":
            defs += line[1:]
        elif line[0] == "struct":
            structs.append((line[1], line[2:]))
        else:
            raise SystemExit("%s: what is %r?" % (path, line[0]))
    return incs, defs, structs


def source(tmp, incs):
    src = os.path.join(tmp, "probe.c")
    open(src, "w").write("#include <stddef.h>\n" + "".join("#include <%s>\n" % h for h in incs))
    return src


def fields(root, lst):
    incs, defs, structs = read_list(lst)
    root = os.path.abspath(root)
    os.environ["LAYOUT_CFLAGS"] = " ".join("-D" + d for d in defs) + " " + os.environ.get("LAYOUT_CFLAGS", "")
    with tempfile.TemporaryDirectory() as tmp:
        obj = os.path.join(tmp, "probe.o")
        subprocess.run([layouts.CC] + layouts.cflags(root) + ["-g", "-gdwarf-4", "-fno-eliminate-unused-debug-types",
                                                              "-c", source(tmp, incs), "-o", obj], check=True)
        found = layouts.structs(obj)
    for name, _ in structs:
        s = found.get("struct " + name)
        if s is None:
            print("# no struct %s" % name, file=sys.stderr)
            continue
        print("struct %s %s" % (name, " ".join(m[0] for m in s["members"] if "." not in m[0])))


def measure(root, lst, out, defined=False):
    incs, defs, structs = read_list(lst)
    root = os.path.abspath(root)
    extra = " ".join("-D" + d for d in defs) if defined else ""
    os.environ["LAYOUT_CFLAGS"] = extra + " " + os.environ.get("LAYOUT_CFLAGS", "")
    exprs = {}
    for name, fs in structs:
        exprs["sizeof(%s)" % name] = "sizeof(struct %s)" % name
        for f in fs:
            exprs["offsetof(%s,%s)" % (name, f)] = "offsetof(struct %s, %s)" % (name, f)
    with tempfile.TemporaryDirectory() as tmp:
        vals = layouts.evaluate(root, source(tmp, incs), exprs, tmp)
    with open(out, "w") as f:
        for k in exprs:
            f.write("%s %s\n" % (k, vals[k] if k in vals else "-"))
    print("%s: %d of %d measured" % (out, len(vals), len(exprs)))


def load(path):
    return dict(line.split() for line in open(path) if line.strip())


def compare(a, b):
    x, y = load(a), load(b)
    bad = [k for k in sorted(set(x) | set(y)) if x.get(k) != y.get(k)]
    for k in bad:
        print("%-48s %s %s" % (k, x.get(k, "absent"), y.get(k, "absent")))
    print("%d numbers compared, %d differ" % (len(set(x) | set(y)), len(bad)))
    return 1 if bad else 0


def gen(plain, defined, lst):
    _, defs, _ = read_list(lst)
    p, d = load(plain), load(defined)
    cond = " && ".join("defined(%s)" % x for x in defs) or "0"
    out = ["/* OpenNDK: structure layouts, field by field.",
           " * Copyright (c) 2026 AmigaChrome Team. MIT licence (see OpenNDK/LICENSE).",
           " *",
           " * Generated by check/layout_numbers.py from tests/layout.list: the",
           " * numbers were measured from the 3.2 NDK's headers with the os32-gcc16",
           " * stove's compiler; only the numbers are kept. tests/run.sh compiles",
           " * this twice, with and without %s." % ", ".join(defs),
           " */"]
    out += ["#include <stddef.h>"]
    for h in read_list(lst)[0]:
        out.append("#include <%s>" % h)
    out += ["",
            "#define S(s, n) _Static_assert(sizeof(struct s) == (n), \"sizeof(struct \" #s \")\")",
            "#define O(s, f, n) _Static_assert(offsetof(struct s, f) == (n), \"offsetof(struct \" #s \", \" #f \")\")",
            ""]

    def line(k, v):
        m = re.match(r"sizeof\((\w+)\)$", k)
        if m:
            return "S(%s, %s);" % (m.group(1), v)
        m = re.match(r"offsetof\((\w+),(\w+)\)$", k)
        return "O(%s, %s, %s);" % (m.group(1), m.group(2), v)

    only_d, only_p = [], []
    for k in d:                                   # the list's order
        vp, vd = p.get(k, "-"), d.get(k, "-")
        if vp == vd and vp != "-":
            out.append(line(k, vp))
        else:
            if vd != "-":
                only_d.append(line(k, vd))
            if vp != "-":
                only_p.append(line(k, vp))
    if only_d or only_p:
        out += ["", "#if %s" % cond] + only_d + ["#else"] + only_p + ["#endif"]
    print("\n".join(out))


if __name__ == "__main__":
    a = sys.argv[1:]
    if a[:1] == ["fields"] and len(a) == 3:
        fields(a[1], a[2])
    elif a[:1] == ["measure"] and len(a) in (4, 5):
        measure(a[1], a[2], a[3], a[4:] == ["defined"])
    elif a[:1] == ["compare"] and len(a) == 3:
        sys.exit(compare(a[1], a[2]))
    elif a[:1] == ["gen"] and len(a) == 4:
        gen(a[1], a[2], a[3])
    else:
        raise SystemExit(__doc__)

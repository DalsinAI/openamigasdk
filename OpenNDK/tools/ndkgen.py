"""OpenNDK's generator: every per-library file from one SFD.

    ndkgen.py [--out DIR] [--stubs DIR] SFD...

From each SFD/<name>_lib.sfd it writes, under DIR (OpenNDK by default):

    FD/<name>_lib.fd               the classic function table
    Include_H/clib/<name>_protos.h C prototypes
    Include_H/inline/<name>.h      GCC inline calls (register asm)
    Include_H/pragmas/<name>_pragmas.h  SAS/C-style #pragma libcall
    Include_H/proto/<name>.h       the one header programs include
    Include_I/lvo/<name>_lib.i     _LVO equates for assembler

With --stubs it also writes one C file per call into that folder: the
link-library stubs lib/build.sh compiles into libamiga.a.

The SFD format is the one the OS's own tools read; OpenNDK/SFD/README.md
describes the subset used here. Every output is generated: edit the SFD and
run this again (tests/run.sh fails when a committed output is stale).
"""
import argparse
import os
import re
import sys

SCRATCH = ("d0", "d1", "a0", "a1")
REGNUM = {"d%d" % i: i for i in range(8)}
REGNUM.update({"a%d" % i: 8 + i for i in range(8)})
BANNER = "Generated by OpenNDK/tools/ndkgen.py from SFD/%s. Do not edit."


class Arg:
    def __init__(self, text):
        self.text = text.strip()
        m = re.search(r"\(\s*\*\s*(?:CONST\s+|const\s+)?(\w+)\s*\)", self.text)
        if m:                                   # a function pointer
            self.name = m.group(1)
            self.type = self.text[:m.start(1)] + self.text[m.end(1):]
            self.decl = self.text
        else:
            m = re.match(r"(.*?)(\w+)\s*((?:\[[^\]]*\])*)$", self.text)
            if not m:
                raise ValueError("cannot read the argument %r" % text)
            self.name = m.group(2)
            self.type = (m.group(1).strip() + (" *" if m.group(3) else "")).strip()
            self.decl = self.text
        self.regs = []

    def kind(self):
        t = re.sub(r"\b(CONST|const)\b", "", self.type).strip()
        if t in ("DOUBLE", "double"):
            return "double"
        if t in ("FLOAT", "float"):
            return "float"
        return "int"


class Func:
    def __init__(self, line, bias, private, version, lineno):
        m = re.match(r"(.+?)\b(\w+)\s*\((.*)\)\s*\(([^()]*)\)\s*$", line)
        if not m:
            raise ValueError("line %d: not a prototype: %s" % (lineno, line))
        self.ret = m.group(1).strip()
        self.name = m.group(2)
        argtext = m.group(3).strip()
        self.regs = [r.strip().lower() for r in re.split(r"[,/-]", m.group(4)) if r.strip()]
        self.bias = bias
        self.private = private
        self.version = version
        self.varargs_of = None                  # the Func this is a varargs form of
        self.alias_of = None
        self.args = []
        self.dots = False
        if argtext and argtext not in ("VOID", "void"):
            for a in split_args(argtext):
                if a.strip() == "...":
                    self.dots = True
                else:
                    self.args.append(Arg(a))
        for r in self.regs:
            if r not in REGNUM:
                raise ValueError("line %d: %s: unknown register %r" % (lineno, self.name, r))

    def assign_regs(self, lineno):
        regs = list(self.regs)
        for a in self.args:
            n = 2 if a.kind() == "double" else 1
            if len(regs) < n:
                raise ValueError("line %d: %s: more arguments than registers" % (lineno, self.name))
            a.regs, regs = regs[:n], regs[n:]
        if regs:
            raise ValueError("line %d: %s: more registers than arguments" % (lineno, self.name))

    def ret_kind(self):
        t = re.sub(r"\b(CONST|const)\b", "", self.ret).strip()
        if t in ("VOID", "void"):
            return "void"
        if t in ("DOUBLE", "double"):
            return "double"
        if t in ("FLOAT", "float"):
            return "float"
        return "int"


def split_args(text):
    out, depth, cur = [], 0, ""
    for ch in text:
        if ch == "(":
            depth += 1
        elif ch == ")":
            depth -= 1
        if ch == "," and depth == 0:
            out.append(cur)
            cur = ""
        else:
            cur += ch
    out.append(cur)
    return [a.strip() for a in out if a.strip()]


class Lib:
    def __init__(self, path, need_base=True):
        self.path = path
        self.need_base = need_base
        self.sfdname = os.path.basename(path)
        self.stem = re.sub(r"_lib\.sfd$", "", self.sfdname)
        self.base = None
        self.basetype = "struct Library *"
        self.libname = None
        self.includes = []
        self.funcs = []                         # every slot and form, in order
        self.copyright = []
        self.parse()

    def parse(self):
        bias, private, version, pending = 30, False, 0, None
        for n, line in self.logical_lines():
            if line.startswith("*"):
                self.copyright.append(line.lstrip("* ").rstrip())
                continue
            if line.startswith("=="):
                word, _, rest = line[2:].partition(" ")
                rest = rest.strip()
                if word == "base":
                    self.base = rest.lstrip("_")
                elif word == "basetype":
                    self.basetype = rest
                elif word == "libname":
                    self.libname = rest
                elif word == "bias":
                    bias = int(rest)
                elif word == "public":
                    private = False
                elif word == "private":
                    private = True
                elif word == "include":
                    self.includes.append(rest)
                elif word == "version":
                    version = int(rest)
                elif word == "reserve":
                    bias += 6 * int(rest)
                elif word in ("varargs", "alias"):
                    pending = word
                elif word == "end":
                    break
                elif word in ("id", "copyright"):
                    pass
                else:
                    raise ValueError("%s:%d: unknown ==%s" % (self.path, n, word))
                continue
            if pending:
                prev = next(f for f in reversed(self.funcs) if not f.varargs_of and not f.alias_of)
                f = Func(line, prev.bias, prev.private, prev.version, n)
                if pending == "varargs":
                    f.varargs_of = prev
                    # the varargs form passes its fixed arguments as the
                    # base form does and the rest on the stack
                    if not f.dots:
                        raise ValueError("%s:%d: ==varargs line without ..." % (self.path, n))
                else:
                    f.alias_of = prev
                    f.assign_regs(n)
                pending = None
            else:
                f = Func(line, bias, private, version, n)
                f.assign_regs(n)
                bias += 6
            self.funcs.append(f)
        if not self.base and self.need_base:
            raise ValueError("%s: no ==base" % self.path)

    def logical_lines(self):
        """The SFD's lines with a prototype written over several lines
        joined into one."""
        def whole(s):
            return s.count("(") == s.count(")") and re.search(r"\)\s*\([^()]*\)\s*$", s)
        buf, start = "", 0
        for n, raw in enumerate(open(self.path, encoding="latin-1").read().splitlines(), 1):
            line = raw.strip()
            if buf:
                buf += " " + line
                if whole(buf):
                    yield start, buf
                    buf = ""
                continue
            if not line:
                continue
            if line.startswith(("*", "==")) or whole(line):
                yield n, line
            else:
                buf, start = line, n
        if buf:
            raise ValueError("line %d: not a prototype: %s" % (start, buf))

    def slots(self):
        return [f for f in self.funcs if not f.varargs_of and not f.alias_of]

    def public(self):
        return [f for f in self.funcs if not f.private]

    @property
    def guard(self):
        return self.stem.upper().replace(".", "_")

    def base_is_arg(self, f):
        return "a6" in f.regs


# ---------------------------------------------------------------- outputs

def header(lib, what):
    return "/* %s: %s.\n * %s\n */\n" % (lib.libname or lib.stem, what, BANNER % lib.sfdname)


def fd(lib):
    out = ["* \"%s\"" % (lib.libname or lib.stem), "* " + BANNER % lib.sfdname,
           "##base _%s" % lib.base]
    bias, private = None, None
    nprivate = 0
    for f in lib.slots():
        if bias is None or f.bias != bias:
            out.append("##bias %d" % f.bias)
        if f.private != private:
            out.append("##private" if f.private else "##public")
            private = f.private
        if f.private and re.match(r"^(private|reserved)\d*$", f.name, re.I):
            nprivate += 1
            name = "%sPrivate%d" % (lib.stem.replace(".", ""), nprivate)
        else:
            name = f.name
        out.append("%s(%s)(%s)" % (name, ",".join(a.name for a in f.args), ",".join(f.regs)))
        bias = f.bias + 6
    out.append("##end")
    return "\n".join(out) + "\n"


def clib(lib):
    g = "CLIB_%s_PROTOS_H" % lib.guard
    out = [header(lib, "C prototypes"), "#ifndef %s\n#define %s\n" % (g, g)]
    for inc in lib.includes or ["<exec/types.h>"]:
        out.append("#include %s" % inc)
    out.append("\n#ifdef __cplusplus\nextern \"C\" {\n#endif\n")
    version = 0
    for f in lib.public():
        if f.version != version and f.version:
            out.append("\n/* From version %d */" % f.version)
            version = f.version
        args = ", ".join([a.decl for a in f.args] + (["..."] if f.dots else [])) or "VOID"
        out.append("%s %s(%s);" % (f.ret, f.name, args))
    out.append("\n#ifdef __cplusplus\n}\n#endif\n\n#endif /* %s */" % g)
    return "\n".join(x for x in out if x is not None) + "\n"


def pragmas(lib):
    g = "PRAGMAS_%s_PRAGMAS_H" % lib.guard
    out = [header(lib, "SAS/C-style pragmas"), "#ifndef %s\n#define %s\n" % (g, g),
           "#ifndef CLIB_%s_PROTOS_H\n#include <clib/%s_protos.h>\n#endif\n" % (lib.guard, lib.stem)]
    for f in lib.public():
        if f.varargs_of:
            base = f.varargs_of
            if any(r in ("a4", "a5", "a6") for r in base.regs) or any(a.kind() != "int" for a in base.args):
                continue
            out.append("#pragma tagcall %s %s %x %s" % (lib.base, f.name, f.bias, regcode(base)))
            continue
        if lib.base_is_arg(f) or any(r in ("a5", "a6") for r in f.regs):
            continue                            # the stub in libamiga.a serves these
        if any(a.kind() != "int" for a in f.args) or f.ret_kind() in ("double", "float"):
            continue
        out.append("#pragma libcall %s %s %x %s" % (lib.base, f.name, f.bias, regcode(f)))
    out.append("\n#endif /* %s */" % g)
    return "\n".join(out) + "\n"


def regcode(f):
    code = "".join("%x" % REGNUM[r] for r in reversed(f.regs))
    return code + "0" + "%x" % len(f.regs)


def lvo_i(lib):
    g = "LVO_%s_LIB_I" % lib.guard
    out = ["* %s: library vector offsets." % (lib.libname or lib.stem), "* " + BANNER % lib.sfdname,
           "\n\tIFND\t%s\n%s\tSET\t1\n" % (g, g)]
    for f in lib.slots():
        if f.private:
            continue
        out.append("_LVO%s\tEQU\t-%d" % (f.name, f.bias))
    for f in lib.funcs:
        if f.alias_of and not f.private:
            out.append("_LVO%s\tEQU\t-%d" % (f.name, f.bias))
    out.append("\n\tENDC\t; %s" % g)
    return "\n".join(out) + "\n"


def proto(lib):
    g = "PROTO_%s_H" % lib.guard
    bt = lib.basetype
    return header(lib, "the header programs include") + """#ifndef {g}
#define {g}

#include <clib/{stem}_protos.h>

#ifndef __NOLIBBASE__
#ifdef __cplusplus
extern "C" {{
#endif
extern {bt}{sp}{base};
#ifdef __cplusplus
}}
#endif
#endif

#if defined(__GNUC__) && defined(__mc68000__) && !defined(__OPENNDK_NO_INLINE__)
#include <inline/{stem}.h>
#elif defined(__SASC) || defined(__STORM__) || defined(__MAXON__) || defined(_DCC)
#include <pragmas/{stem}_pragmas.h>
#endif

#endif /* {g} */
""".format(g=g, stem=lib.stem, bt=bt, base=lib.base, sp="" if bt.endswith("*") else " ")


# The inline calls. Each call is a static inline function holding the
# register binding and the jsr, behind a macro of the call's own name, so
# that the clib prototype and the macro live side by side, and the base can
# be swapped with <NAME>_BASE_NAME as the OS's tools have always allowed.

def inline(lib):
    g = "INLINE_%s_H" % lib.guard
    bn = "%s_BASE_NAME" % lib.guard
    out = [header(lib, "GCC inline calls"), "#ifndef %s\n#define %s\n" % (g, g),
           "#ifndef CLIB_%s_PROTOS_H\n#include <clib/%s_protos.h>\n#endif\n" % (lib.guard, lib.stem),
           "#ifndef %s\n#define %s %s\n#endif\n" % (bn, bn, lib.base),
           base_decl(lib),
           "#ifndef __OPENNDK_FPCLOBBER\n#ifdef __HAVE_68881__\n"
           "#define __OPENNDK_FPCLOBBER \"fp0\", \"fp1\",\n#else\n"
           "#define __OPENNDK_FPCLOBBER\n#endif\n#endif\n"]
    for f in lib.public():
        if f.alias_of and same_call(f, f.alias_of):
            out.append("#define %s(...) %s(__VA_ARGS__)\n" % (f.name, f.alias_of.name) if f.args
                       else "#define %s() %s()\n" % (f.name, f.alias_of.name))
            continue
        if f.varargs_of:
            # an inline function of its own that hands the arguments on the
            # stack to the tag/array form, as NDK 3.2's inline headers do,
            # so no amiga.lib is needed; with NO_INLINE_STDARG, the real
            # function in libamiga.a. Both macros cast the fixed arguments.
            out.append(varargs_inline(lib, f))
            continue
        out.append(inline_func(lib, f, bn))
    out.append("#endif /* %s */" % g)
    return "\n".join(out) + "\n"


def varargs_macro(f):
    fixed = f.args[:len(f.varargs_of.args) - 1]
    if not fixed:
        return ""
    names = [a.name for a in fixed]
    return "#define %s(%s, ...) (%s)(%s, ##__VA_ARGS__)\n" % (
        f.name, ", ".join(names), f.name, ", ".join("(%s)(%s)" % (a.type, a.name) for a in fixed))


def varargs_inline(lib, f):
    g = f.varargs_of
    old = varargs_macro(f)
    if lib.base_is_arg(g) or len(g.args) < 1:
        return old
    fixed = f.args[:len(g.args) - 1]
    rest = f.args[len(fixed):]
    if not fixed and not rest:
        return old
    last = g.args[-1]
    if rest:
        addr = "(%s)&%s" % (last.type, rest[0].name)
    else:
        addr = "(%s)((ULONG)&%s + sizeof(%s))" % (last.type, fixed[-1].name, fixed[-1].name)
    fname = "___%s_%s" % (lib.stem.replace(".", "_"), f.name)
    params = ["%s __ndk_base" % base_t(lib)] + [a.decl for a in fixed + rest] + ["..."]
    call = "__%s_%s(__ndk_base%s)" % (lib.stem.replace(".", "_"), g.name,
                                      "".join(", (%s)(%s)" % (a.type, a.name) for a in fixed) + ", " + addr)
    body = ("\t%s;" % call) if f.ret_kind() == "void" else ("\treturn %s;" % call)
    names = [a.name for a in fixed]
    margs = ["(%s)(%s)" % (base_t(lib), "%s_BASE_NAME" % lib.guard)] + ["(%s)(%s)" % (a.type, a.name) for a in fixed]
    if names:
        macro = "#define %s(%s, ...) %s(%s, ##__VA_ARGS__)" % (f.name, ", ".join(names), fname, ", ".join(margs))
    else:
        macro = "#define %s(...) %s(%s, __VA_ARGS__)" % (f.name, fname, ", ".join(margs))
    # never inlined or cloned: the arguments after the named ones must stay
    # on the stack beside it, and GCC drops them when it inlines a call that
    # has no va_start, or copies a constant first one into a clone's frame
    return ("#ifndef NO_INLINE_STDARG\nstatic __attribute__((__noinline__, __noclone__, __unused__)) %s\n%s(%s)\n{\n%s\n}\n%s\n#else\n%s#endif\n"
            % (f.ret, fname, ", ".join(params), body, macro, old or ""))


def same_call(f, g):
    """An alias that takes the same registers is a plain second name; one
    that takes fewer (dos's DoPkt0 to DoPkt4) gets an inline of its own."""
    return f.regs == g.regs


def base_t(lib):
    return "__%s_base_t" % lib.stem.replace(".", "_")


def base_decl(lib):
    """Declare the base's structure at file scope, so the inline functions'
    parameter names the same type the program's base variable has, and a
    typedef of the base type that the call macros cast to: a program may
    #define the base's own name (GfxBase) after this header, and a typedef
    can't be expanded by that."""
    m = re.match(r"\s*struct\s+(\w+)\s*\*\s*$", lib.basetype)
    return ("struct %s;\n" % m.group(1) if m else "") + "typedef %s%s%s;\n" % (
        lib.basetype, "" if lib.basetype.endswith("*") else " ", base_t(lib))


def cast_in(a, var):
    k = a.kind()
    if k == "int":
        return ["\tregister ULONG %s __asm(\"%s\") = (ULONG)(%s);" % (var, a.regs[0], a.name)]
    if k == "float":
        return ["\tunion { FLOAT f; ULONG u; } %s_u; %s_u.f = %s;" % (var, var, a.name),
                "\tregister ULONG %s __asm(\"%s\") = %s_u.u;" % (var, a.regs[0], var)]
    return ["\tunion { DOUBLE d; ULONG u[2]; } %s_u; %s_u.d = %s;" % (var, var, a.name),
            "\tregister ULONG %s __asm(\"%s\") = %s_u.u[0];" % (var, a.regs[0], var),
            "\tregister ULONG %s_lo __asm(\"%s\") = %s_u.u[1];" % (var, a.regs[1], var)]


def inline_func(lib, f, bn):
    fname = "__%s_%s" % (lib.stem.replace(".", "_"), f.name)
    base_arg = lib.base_is_arg(f)
    params = ([] if base_arg else ["%s__base" % (lib.basetype + ("" if lib.basetype.endswith("*") else " "))])
    params += [a.decl for a in f.args]
    body = []
    regvars = {}                                 # register -> variable name
    special = []                                 # a4/a5 arguments, loaded inside the asm
    for a in f.args:
        if a.regs[0] in ("a4", "a5"):
            if a.kind() != "int":
                raise ValueError("%s: a non-integer argument in %s" % (f.name, a.regs[0]))
            special.append(a)
            continue
        var = "_" + a.regs[0]
        body += cast_in(a, var)
        regvars[a.regs[0]] = var
        if len(a.regs) > 1:
            regvars[a.regs[1]] = var + "_lo"
    if not base_arg:
        body.append("\tregister %s_a6 __asm(\"a6\") = __base;" % (lib.basetype + ("" if lib.basetype.endswith("*") else " ")))
        regvars["a6"] = "_a6"
    rk = f.ret_kind()
    outs, ins = [], []
    for r in SCRATCH:
        if r in regvars:
            outs.append('"+r" (%s)' % regvars[r])
        else:
            body.append("\tregister ULONG _%s __asm(\"%s\");" % (r, r))
            regvars[r] = "_" + r
            outs.append('"=r" (%s)' % regvars[r])
    for r, v in sorted(regvars.items()):
        if r not in SCRATCH:
            ins.append('"r" (%s)' % v)
    asm = []
    for i, a in enumerate(special):
        ins.append('[s%d] "r" ((ULONG)(%s))' % (i, a.name))
    for i, a in enumerate(special):
        asm.append("move.l %%/%s,-(%%/sp)" % a.regs[0])
    for i, a in enumerate(special):
        asm.append("move.l %%[s%d],%%/%s" % (i, a.regs[0]))
    asm.append("jsr -%d(%%/a6)" % f.bias)
    for a in reversed(special):
        asm.append("move.l (%%/sp)+,%%/%s" % a.regs[0])
    body.append("\t__asm__ __volatile__ (\"%s\"" % "\\n\\t".join(asm))
    body.append("\t\t: %s" % ", ".join(outs))
    body.append("\t\t: %s" % ", ".join(ins) if ins else "\t\t:")
    body.append("\t\t: __OPENNDK_FPCLOBBER \"cc\", \"memory\");")
    if rk == "int":
        body.append("\treturn (%s)%s;" % (f.ret, regvars["d0"]))
    elif rk == "float":
        body.append("\t{ union { ULONG u; FLOAT f; } _r; _r.u = %s; return _r.f; }" % regvars["d0"])
    elif rk == "double":
        body.append("\t{ union { ULONG u[2]; DOUBLE d; } _r; _r.u[0] = %s; _r.u[1] = %s; return _r.d; }"
                    % (regvars["d0"], regvars["d1"]))
    else:
        body.append("\t" + " ".join("(void)%s;" % regvars[r] for r in SCRATCH))
    sig = "static __inline__ %s\n%s(%s)" % (f.ret, fname, ", ".join(params) or "void")
    # each argument is cast to the call's own type, as the vendor's inline
    # macros do: a string literal or a char * goes to a CONST_STRPTR, and an
    # int to a ULONG, without a warning under -Werror
    # the base too, as NDK 3.2's inline headers take any pointer there (a
    # program's own struct Library *LocaleBase, say)
    callargs = ([] if base_arg else ["(%s)(%s)" % (base_t(lib), bn)]) + ["(%s)(%s)" % (a.type, a.name) for a in f.args]
    macro = "#define %s(%s) %s(%s)" % (f.name, ", ".join(a.name for a in f.args), fname,
                                         ", ".join(callargs))
    if not base_arg:
        # __<call>_base(base, ...): the call through a base of the caller's,
        # as the GCC packaging of NDK 3.2 (sfdc's inline headers) has it
        names = ["__ndk_b"] + [a.name for a in f.args]
        bargs = ["(%s)(__ndk_b)" % base_t(lib)] + callargs[1:]
        macro += "\n#define __%s_base(%s) %s(%s)" % (f.name, ", ".join(names), fname, ", ".join(bargs))
    return "%s\n{\n%s\n}\n%s\n" % (sig, "\n".join(body), macro)



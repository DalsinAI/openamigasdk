def stubs(lib, outdir):
    """One C file per call for libamiga.a: a real function of the call's
    name that takes its arguments on the stack and calls through the base."""
    os.makedirs(outdir, exist_ok=True)
    written = []
    for f in lib.public():
        if f.alias_of and same_call(f, f.alias_of):
            continue
        path = os.path.join(outdir, "%s_%s.c" % (lib.stem.replace(".", "_"), f.name))
        src = ["/* " + BANNER % lib.sfdname + " */",
               "#define __NOLIBBASE__",
               "#include <inline/%s.h>" % lib.stem,
               "#undef %s" % f.name]
        if f.varargs_of:
            base = f.varargs_of
            nfixed = len(base.args) - 1
            fixed, named = f.args[:nfixed], f.args[nfixed:]
            decl = ", ".join([a.decl for a in f.args] + ["..."])
            src.insert(1, "#include <stdarg.h>")
            src.append("#undef %s" % base.name)
            src.append("extern %s%s%s;" % (lib.basetype, "" if lib.basetype.endswith("*") else " ", lib.base))
            src.append("%s %s(%s)\n{" % (f.ret, f.name, decl))
            call_args = [] if lib.base_is_arg(base) else ["(%s)" % lib.base]
            call_args += [a.name for a in fixed]
            if named:
                # 68k arguments sit side by side on the stack: the first
                # variable argument starts the array the base form takes
                call_args.append("(%s)&%s" % (base.args[-1].type, named[0].name))
                pre = ""
            else:
                src.append("\tva_list _ap;\n\tva_start(_ap, %s);" % f.args[-1].name)
                call_args.append("(%s)_ap" % base.args[-1].type)
            fn = "__%s_%s" % (lib.stem.replace(".", "_"), base.name)
            if f.ret_kind() == "void":
                src.append("\t%s(%s);" % (fn, ", ".join(call_args)))
                if not named:
                    src.append("\tva_end(_ap);")
                src.append("}")
            else:
                src.append("\t%s _r = %s(%s);" % (f.ret, fn, ", ".join(call_args)))
                if not named:
                    src.append("\tva_end(_ap);")
                src.append("\treturn _r;\n}")
        else:
            src.append("extern %s%s%s;" % (lib.basetype, "" if lib.basetype.endswith("*") else " ", lib.base))
            decl = ", ".join(a.decl for a in f.args) or "VOID"
            fn = "__%s_%s" % (lib.stem.replace(".", "_"), f.name)
            call_args = ([] if lib.base_is_arg(f) else [lib.base]) + [a.name for a in f.args]
            ret = "" if f.ret_kind() == "void" else "return "
            src.append("%s %s(%s)\n{\n\t%s%s(%s);\n}" % (f.ret, f.name, decl, ret, fn, ", ".join(call_args)))
        open(path, "w").write("\n".join(src) + "\n")
        written.append(path)
    return written


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    old = open(path).read() if os.path.exists(path) else None
    if old != text:
        open(path, "w").write(text)
        return True
    return False


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
    ap.add_argument("--stubs")
    ap.add_argument("--check", action="store_true", help="exit 1 if any output would change")
    ap.add_argument("sfd", nargs="+")
    o = ap.parse_args()
    changed = []
    for path in o.sfd:
        lib = Lib(path)
        files = {
            "FD/%s_lib.fd" % lib.stem: fd(lib),
            "Include_H/clib/%s_protos.h" % lib.stem: clib(lib),
            "Include_H/pragmas/%s_pragmas.h" % lib.stem: pragmas(lib),
            "Include_H/inline/%s.h" % lib.stem: inline(lib),
            "Include_H/proto/%s.h" % lib.stem: proto(lib),
            "Include_I/lvo/%s_lib.i" % lib.stem: lvo_i(lib),
        }
        for rel, text in files.items():
            dest = os.path.join(o.out, rel)
            if o.check:
                if not os.path.exists(dest) or open(dest).read() != text:
                    changed.append(rel)
            elif write(dest, text):
                changed.append(rel)
        if o.stubs:
            stubs(lib, o.stubs)
    if o.check and changed:
        print("stale generated files (run tools/ndkgen.py SFD/*.sfd):\n  " + "\n  ".join(changed))
        sys.exit(1)


if __name__ == "__main__":
    main()
